export const EXPORT_LANG = Object.freeze({
  EN: 'en',
  AR: 'ar',
});

export function normalizeExportLanguage(raw) {
  const v = String(raw || '')
    .trim()
    .toLowerCase();
  if (v === 'ar' || v === 'arabic' || v === 'العربية') {
    return EXPORT_LANG.AR;
  }
  return EXPORT_LANG.EN;
}

