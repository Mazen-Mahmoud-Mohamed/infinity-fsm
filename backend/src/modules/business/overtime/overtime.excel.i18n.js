export function excelStrings(lang) {
  return normalizeExportLanguage(lang) === EXPORT_LANG.AR ? AR : EN;
}

/** Human-readable duration for Excel text cells (never decimal hours). */
export function formatDurationProseFromMinutes(minutes, lang = EXPORT_LANG.EN) {
  const t = excelStrings(lang);
  if (minutes === null || minutes === undefined || minutes === '') {
    return t.dash;
  }
  const n = Number(minutes);
  if (!Number.isFinite(n)) return t.dash;
  const safe = Math.max(0, Math.round(n));
  const h = Math.floor(safe / 60);
  const m = safe % 60;
  if (h === 0) {
    return m === 1 ? t.minuteOne : t.minutes(m);
  }
  const hLabel = h === 1 ? t.hourOne : t.hours(h);
  if (m === 0) {
    return hLabel;
  }
  const mLabel = m === 1 ? t.minuteOne : t.minutes(m);
  return t.hoursAndMinutes(h, hLabel, m, mLabel);
}

export function formatDurationProseFromHours(hours, lang = EXPORT_LANG.EN) {
  const t = excelStrings(lang);
  if (hours === null || hours === undefined || hours === '') return t.dash;
  if (hours === t.dash || hours === '—') return t.dash;
  const n = Number(hours);
  if (!Number.isFinite(n)) return t.dash;
  return formatDurationProseFromMinutes(Math.round(n * 60), lang);
}

export function statusLabel(status, lang = EXPORT_LANG.EN) {
  const t = excelStrings(lang);
  switch (String(status || '').toUpperCase()) {
    case 'APPROVED':
      return t.statusApproved;
    case 'PENDING_REVIEW':
      return t.statusPendingReview;
    case 'REJECTED':
      return t.statusRejected;
    case 'RUNNING':
      return t.statusRunning;
    case 'CANCELLED':
      return t.statusCancelled;
    case 'PENDING_SYNC':
      return t.statusPendingSync;
    default:
      return status || t.dash;
  }
}

export function typeLabel(type, lang = EXPORT_LANG.EN) {
  const t = excelStrings(lang);
  switch (String(type || '').toUpperCase()) {
    case 'NORMAL':
      return t.typeNormal;
    case 'TRAVEL':
      return t.typeTravel;
    default:
      return type || t.dash;
  }
}

/** Overnight applies to Travel overtime only. */
export function overnightLabel(record, lang = EXPORT_LANG.EN) {
  const t = excelStrings(lang);
  if (String(record?.type || '').toUpperCase() !== 'TRAVEL') return t.dash;
  return record.isOvernight ? t.yes : t.no;
}

